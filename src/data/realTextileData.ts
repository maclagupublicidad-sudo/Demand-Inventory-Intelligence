export function buildGarmentsFromRelational(
  productos: TablaProducto[],
  fichas: TablaFichaTecnica[],
  boms: TablaBOMItem[],
  materias: TablaMateriaPrima[]
): Garment[] {
  const matMap = new Map<string, TablaMateriaPrima>();
  materias.forEach((m) => matMap.set(m.SKU_Material.toUpperCase(), m));

  const fichaMap = new Map<string, TablaFichaTecnica>();
  fichas.forEach((f) => fichaMap.set(f.SKU_Prenda.toUpperCase(), f));

  return productos.map((p) => {
    const ficha = fichaMap.get(p.SKU_Prenda.toUpperCase()) || {
      Tiempo_Corte_Min: 1.5,
      SAM_Confeccion_Min: 10.0,
      Tiempo_Acabados_Min: 1.5,
      Tarifa_Minuto_Interno_COP: 280,
      Tarifa_Maquila_Corte_COP: 1000,
      Tarifa_Maquila_Confeccion_COP: 4500,
      Tarifa_Maquila_Acabados_COP: 1000,
      Merma_Corte_Porcentaje: 4.0,
      Notas_Ficha_Tecnica: '',
    };

    const prodBOMs = boms.filter((b) => b.SKU_Prenda.toUpperCase() === p.SKU_Prenda.toUpperCase());

    const bomItems = prodBOMs.map((b) => {
      const mat = matMap.get(b.SKU_Material.toUpperCase());
      return {
        rawMaterialId: mat ? mat.id_material : `mat-${b.SKU_Material.toLowerCase()}`,
        rawMaterialName: mat ? mat.Nombre_Material : b.Nombre_Material || b.SKU_Material,
        category: mat ? mat.Categoria : (b.Categoria_Material || 'Tela'),
        quantityPerGarment: b.Consumo_Por_Prenda,
        unit: b.Unidad_Medida,
        wastePercent: b.Merma_Corte_Porcentaje,
      };
    });

    const totalMinutes = ficha.Tiempo_Corte_Min + ficha.SAM_Confeccion_Min + ficha.Tiempo_Acabados_Min;
    const internalLaborCost = Math.round(totalMinutes * ficha.Tarifa_Minuto_Interno_COP);
    const internalOverheadCost = Math.round(totalMinutes * 95);

    let rawMaterialsCost = 0;
    bomItems.forEach((item) => {
      const mat = matMap.get(item.rawMaterialId.replace('mat-', '').toUpperCase());
      const cost = mat ? mat.Costo_Unitario_COP : 1000;
      rawMaterialsCost += item.quantityPerGarment * (1 + item.wastePercent / 100) * cost;
    });
    rawMaterialsCost = Math.round(rawMaterialsCost);

    const totalInternalCost = rawMaterialsCost + internalLaborCost + internalOverheadCost;
    const maquilaTotal = rawMaterialsCost + ficha.Tarifa_Maquila_Corte_COP + ficha.Tarifa_Maquila_Confeccion_COP + ficha.Tarifa_Maquila_Acabados_COP + 900;

    return {
      id: p.id_producto,
      sku: p.SKU_Prenda,
      name: p.Nombre_Prenda,
      category: p.Categoria_Prenda,
      targetSales: p.Meta_Ventas_Ciclo,
      historicalMonthlyAverage: Math.round(p.Meta_Ventas_Ciclo / 3),
      retailPrice: p.PVP_COP,
      costEstimate: totalInternalCost,
      finishedGoodsStock: p.stock_producto_terminado || 0,
      productionWIP: p.unidades_en_proceso || 0,
      bom: bomItems,
      productionTimes: {
        cuttingMinutesPerGarment: ficha.Tiempo_Corte_Min,
        sewingSAM: ficha.SAM_Confeccion_Min,
        finishingMinutesPerGarment: ficha.Tiempo_Acabados_Min,
        totalManufacturingMinutes: totalMinutes,
        standardBatchSize: 300,
        totalCycleDays: 7,
      },
      costing: {
        rawMaterialsCost,
        internalLaborRatePerMinute: ficha.Tarifa_Minuto_Interno_COP,
        internalOverheadRatePerMinute: 95,
        internalLaborCost,
        internalOverheadCost,
        totalInternalCost,
        maquilaCuttingRate: ficha.Tarifa_Maquila_Corte_COP,
        maquilaSewingRate: ficha.Tarifa_Maquila_Confeccion_COP,
        maquilaFinishingRate: ficha.Tarifa_Maquila_Acabados_COP,
        maquilaLogisticsCost: 900,
        totalMaquilaCost: maquilaTotal,
        recommendedSellingPrice: p.PVP_COP,
        internalProfitMarginPercent: Math.round(((p.PVP_COP - totalInternalCost) / p.PVP_COP) * 100),
        maquilaProfitMarginPercent: Math.round(((p.PVP_COP - maquilaTotal) / p.PVP_COP) * 100),
      },
      techPackNotes: ficha.Notas_Ficha_Tecnica,
      isActive: p.estado === 'Activo',
    };
  });
}

